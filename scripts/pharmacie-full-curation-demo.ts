/**
 * Full live curation demo: runs the audit_duplicates workflow on a real
 * Pharmacie subtree and prints the markdown report.
 *
 * Usage: bun run scripts/pharmacie-full-curation-demo.ts [folderid] [minSize]
 */
import { listRecursiveHandler } from '../src/core/tools/list-recursive.js';
import { _rangeReadHandler } from '../src/core/tools/range-read.js';
import { checksumGroupHandler } from '../src/core/tools/checksum-group.js';

const folderid = Number(process.argv[2] ?? 12758060591);
const minSize = Number(process.argv[3] ?? 1024);

console.error(`\n=== LIVE CURATION DEMO: audit_duplicates on folder ${folderid} ===\n`);

// 1. LIST RECURSIVE
console.error('Step 1/4: list_recursive...');
const listing = await listRecursiveHandler({ folderid, maxdepth: 6, limit: 5000 }, undefined);
const allFiles = (listing.structuredContent as { files: Array<Record<string, unknown>> }).files;
console.error(`  Total files: ${allFiles.length}`);

// 2. FILTER BY SIZE
const candidates = allFiles.filter((f) => (f.size as number) >= minSize);
console.error(`  Files >= ${minSize} bytes: ${candidates.length}`);

// 3. CHECKSUM GROUP
console.error('Step 2/4: checksum_group...');
const filesForChecksum = candidates.map((f) => ({
  fileid: f.fileid as number,
  size: f.size as number,
  hash: f.hash as number,
}));
const grouped = await checksumGroupHandler({ files: filesForChecksum, includeSingletons: true }, undefined);
const stats = (grouped.structuredContent as { stats: Record<string, unknown> }).stats;
const _digests = (grouped.structuredContent as { digests: Record<string, string> }).digests;
const duplicates = (grouped.structuredContent as { duplicates: Array<Record<string, unknown>> }).duplicates;

console.error(`  Checksumfile calls: ${stats.apiCalls}`);
console.error(`  Groups: ${stats.groups}, duplicates: ${stats.duplicates}, redundant copies: ${stats.redundantCopies}, bytes reclaimable: ${Number(stats.bytesReclaimable).toLocaleString()}`);

// 4. BUILD REPORT
const reclaimMB = Number(stats.bytesReclaimable) / 1024 / 1024;
const lines: string[] = [
  '# Live Curation Report: audit_duplicates',
  '',
  `**Folder:** \`${folderid}\`  **Min size:** ${minSize} bytes`,
  `**Total files scanned:** ${allFiles.length}  **Candidates:** ${candidates.length}`,
  `**Checksumfile calls:** ${stats.apiCalls} (one per candidate group, not per file)`,
  `**Groups:** ${stats.groups}  **Duplicate groups:** ${stats.duplicates}  **Redundant copies:** ${stats.redundantCopies}  **Reclaimable:** ${reclaimMB.toFixed(2)} MB`,
  '',
];

if (duplicates && duplicates.length > 0) {
  lines.push('## Duplicate Groups');
  lines.push('');
  for (const group of duplicates) {
    const sha1 = group.sha1 as string;
    const size = group.size as number;
    const fileids = group.fileids as number[];
    lines.push(`### SHA-1 \`${sha1}\` (${(size / 1024).toFixed(1)} KB × ${fileids.length})`);
    lines.push('');
    for (const id of fileids) {
      const meta = allFiles.find((f) => f.fileid === id);
      lines.push(`- \`${meta?.path}\` (${meta?.size} bytes, hash ${meta?.hash})`);
    }
    lines.push('');
  }
} else {
  lines.push('> No duplicate groups found at this size threshold.');
}

lines.push('---');
lines.push('*Generated by live curation demo using `list_recursive` → `checksum_group`*');

const report = lines.join('\n');
console.log(report);

// Also write to file for easy reading
const fs = await import('node:fs/promises');
const outFile = `/tmp/pharmacie-curation-report-${Date.now()}.md`;
await fs.writeFile(outFile, report);
console.error(`\nReport written to ${outFile}`);